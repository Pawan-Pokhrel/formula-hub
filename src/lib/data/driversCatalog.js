export function getDriverBySlug(slug) {
	return DRIVER_CATALOG.find((driver) => driver.slug === slug) || null;
}

export function getDriversByTeam() {
	const grouped = {};
	for (const driver of DRIVER_CATALOG) {
		if (!grouped[driver.teamName]) grouped[driver.teamName] = [];
		grouped[driver.teamName].push(driver);
	}
	return grouped;
}

export function getAllTeams() {
	return Array.from(
		new Set(DRIVER_CATALOG.map((driver) => driver.teamName))
	).sort();
}
